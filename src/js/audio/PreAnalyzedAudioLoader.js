/**
 * PreAnalyzedAudioLoader - Loads and processes pre-analyzed audio data
 * Provides access to pre-computed audio features for optimized performance
 *
 * @package SonoiteTheme
 * @version 1.0.0
 */

import { dlog, dwarn, derr } from '../utils/devlog.js';

export class PreAnalyzedAudioLoader {
    constructor() {
        this.analysisCache = new Map();
        this.currentAnalysis = null;
        this.playbackStartTime = null;
        this.lastFrameIndex = 0;

        // Interpolation settings
        this.interpolationEnabled = true;
        this.smoothingFactor = 0.8;
        this.lastInterpolatedData = null;
    }

    /**
     * Load pre-analyzed audio data for a track
     * @param {string} trackSlug - Track identifier (e.g., 'sonoite')
     * @returns {Promise<Object>} Analysis data object
     */
    async loadAnalysis(trackSlug) {
        // Check cache first
        if (this.analysisCache.has(trackSlug)) {
            this.currentAnalysis = this.analysisCache.get(trackSlug);
            dlog(`📊 Using cached analysis for: ${trackSlug}`);
            return this.currentAnalysis;
        }

        try {
            // Construct analysis file path
            const analysisPath = this.getAnalysisPath(trackSlug);

            dlog(`📊 Loading pre-analyzed audio data: ${analysisPath}`);
            const response = await fetch(analysisPath);

            if (!response.ok) {
                throw new Error(`Failed to load analysis: ${response.status}`);
            }

            const analysisData = await response.json();
            const splitData = await this.loadSplitAnalysis(trackSlug);

            // Process and optimize the data
            const processedData = this.processAnalysisData(analysisData, splitData);

            // Cache the processed data
            this.analysisCache.set(trackSlug, processedData);
            this.currentAnalysis = processedData;

            dlog(`📊 Pre-analyzed audio data loaded successfully for: ${trackSlug}`);
            dlog(`📊 Analysis contains ${processedData.frameCount} frames over ${processedData.duration}s`);

            return processedData;

        } catch (error) {
            derr(`Failed to load pre-analyzed audio data for ${trackSlug}:`, error);
            return null;
        }
    }

    /**
     * Get analysis file path
     */
    getAnalysisPath(trackSlug) {
        // Try multiple possible paths
        const paths = [
            `/homem/wp-content/themes/sonoite-theme/public/assets/journeys/analysis/${trackSlug}.analysis.json`,
            `/wp-content/themes/sonoite-theme/public/assets/journeys/analysis/${trackSlug}.analysis.json`,
            `./public/assets/journeys/analysis/${trackSlug}.analysis.json`
        ];

        // Use WordPress data if available
        if (window.sonoiteData?.themeUrl) {
            return `${window.sonoiteData.themeUrl}/public/assets/journeys/analysis/${trackSlug}.analysis.json`;
        }

        return paths[0]; // Default path
    }

    /**
     * Get split analysis file path
     */
    getSplitAnalysisPath(trackSlug, fileName) {
        if (window.sonoiteData?.themeUrl) {
            return `${window.sonoiteData.themeUrl}/public/assets/journeys/analysis/${trackSlug}/${fileName}`;
        }

        return `/homem/wp-content/themes/sonoite-theme/public/assets/journeys/analysis/${trackSlug}/${fileName}`;
    }

    /**
     * Load optional split analysis files generated by the detailed analyzer.
     */
    async loadSplitAnalysis(trackSlug) {
        try {
            const response = await fetch(this.getSplitAnalysisPath(trackSlug, 'timeline.json'));

            if (!response.ok) {
                return {};
            }

            return {
                timeline: await response.json()
            };
        } catch (error) {
            dwarn(`Split audio timeline unavailable for ${trackSlug}:`, error);
            return {};
        }
    }

    /**
     * Process raw analysis data for efficient access
     */
    processAnalysisData(rawData, splitData = {}) {
        const processed = {
            track: rawData.track,
            duration: rawData.durationSeconds,
            frameCount: rawData.framesAnalyzed,
            frameSize: rawData.frameSize,
            hopSize: rawData.hopSize,
            sampleRate: rawData.sampleRate,
            frameInterval: rawData.hopSize && rawData.sampleRate ? rawData.hopSize / rawData.sampleRate : 0,
            segmentCount: Array.isArray(rawData.segments) ? rawData.segments.length : 0,
            peaks: rawData.peaks || {},

            // Pre-process time-series data for fast lookup
            timeFrames: [],

            // Feature statistics for normalization
            stats: rawData.features || {},

            // Timestamp
            analysisTimestamp: rawData.analysisTimestamp
        };

        if (splitData.timeline?.timeline) {
            processed.timeFrames = this.extractTimelineFrames(splitData.timeline);
            processed.frameCount = processed.timeFrames.length;
            processed.frameInterval = (splitData.timeline.intervalMs || 500) / 1000;
            processed.analysisSource = 'split-timeline';
        } else if (Array.isArray(rawData.timeSeries)) {
            processed.timeFrames = this.extractTimeFrames(rawData.timeSeries, processed);
            processed.frameCount = processed.timeFrames.length;
            processed.analysisSource = 'time-series';
        } else if (Array.isArray(rawData.segments)) {
            processed.timeFrames = this.extractSegmentFrames(rawData.segments);
            processed.frameCount = processed.timeFrames.length;
            processed.frameInterval = this.getSegmentInterval(rawData.segments);
            processed.analysisSource = 'segments';
        } else {
            processed.analysisSource = 'metadata-only';
        }

        return processed;
    }

    /**
     * Extract frame-by-frame audio features
     */
    extractTimeFrames(timeSeries, analysis) {
        if (!timeSeries || !Array.isArray(timeSeries)) {
            dwarn('No time series data found in analysis');
            return [];
        }

        return timeSeries.map((frame, index) => ({
            time: (index * (analysis?.hopSize || 1024)) / (analysis?.sampleRate || 44100),
            rms: frame.rms || 0,
            energy: frame.energy || 0,
            spectralCentroid: frame.spectralCentroid || 0,
            spectralRolloff: frame.spectralRolloff || 0,
            zeroCrossingRate: frame.zeroCrossingRate || 0,
            // Derived features
            loudness: Math.sqrt(frame.energy || 0),
            brightness: (frame.spectralCentroid || 0) / 8000 // Normalize to 0-1
        }));
    }

    /**
     * Extract detailed 0.5s timeline frames from split analyzer output.
     */
    extractTimelineFrames(timelineData) {
        if (!Array.isArray(timelineData.timeline)) {
            return [];
        }

        return timelineData.timeline.map((frame, index) => ({
            time: Number.isFinite(frame.t) ? frame.t : index * ((timelineData.intervalMs || 500) / 1000),
            rms: frame.rms || 0,
            energy: frame.energy || 0,
            loudness: frame.loudness || 0,
            spectralCentroid: frame.centroid || frame.spectralCentroid || 0,
            spectralRolloff: frame.rolloff || frame.spectralRolloff || 0,
            flatness: frame.flatness || 0,
            brightness: frame.centroid || frame.spectralCentroid || 0
        }));
    }

    /**
     * Extract coarse frames from aggregate 4s segment summaries.
     */
    extractSegmentFrames(segments) {
        return segments.map(segment => ({
            time: segment.start || 0,
            end: segment.end,
            rms: segment.rms || 0,
            energy: segment.energy || 0,
            loudness: segment.loudness || 0,
            spectralCentroid: segment.spectralCentroid || 0,
            spectralRolloff: segment.spectralRolloff || 0,
            zeroCrossingRate: segment.zcr || 0,
            brightness: segment.spectralCentroid || 0
        }));
    }

    getSegmentInterval(segments) {
        if (!Array.isArray(segments) || segments.length === 0) {
            return 0;
        }

        const first = segments[0];
        return Math.max(0.001, (first.end || 0) - (first.start || 0));
    }

    /**
     * Get audio data for current playback time
     * @param {number} currentTime - Current playback time in seconds
     * @returns {Object} Audio analysis data
     */
    getAudioDataAtTime(currentTime) {
        if (!this.currentAnalysis || !this.currentAnalysis.timeFrames) {
            return this.getFallbackData();
        }

        const frameIndex = this.getFrameIndexForTime(currentTime);
        const frame = this.currentAnalysis.timeFrames[frameIndex];

        if (!frame) {
            return this.getFallbackData();
        }

        // Convert to Visual Layer API format
        const audioData = this.convertToVisualLayerFormat(frame);

        // Apply smoothing if enabled
        if (this.interpolationEnabled && this.lastInterpolatedData) {
            return this.interpolateAudioData(audioData, this.lastInterpolatedData);
        }

        this.lastInterpolatedData = audioData;
        return audioData;
    }

    /**
     * Find frame index for given time
     */
    getFrameIndexForTime(time) {
        if (!this.currentAnalysis) {
            return 0;
        }

        const frameTime = this.currentAnalysis.frameInterval ||
            (this.currentAnalysis.hopSize / this.currentAnalysis.sampleRate);
        const index = Math.floor(time / frameTime);

        return Math.max(0, Math.min(index, this.currentAnalysis.frameCount - 1));
    }

    /**
     * Convert analysis frame to Visual Layer API format
     */
    convertToVisualLayerFormat(frame) {
        // Map measured feature ranges to the 0-1 visual layer contract.
        const rawCentroid = frame.spectralCentroid || frame.centroid || frame.brightness || 0;
        const loudness = this.normalizeFeature(frame.loudness || Math.sqrt(frame.energy || 0), 'loudness', 80);
        const brightness = this.normalizeFeature(rawCentroid, 'spectralCentroid', 8000);
        const energy = this.normalizeFeature(frame.energy || frame.rms || 0, 'energy', 1);
        const rms = this.normalizeFeature(frame.rms || 0, 'rms', 1);

        return {
            // Core frequency bands (approximated from analysis)
            bass: Math.min(1, energy * (1 - brightness) * 1.2),
            mid: Math.min(1, energy * 0.8),
            treble: Math.min(1, energy * brightness * 1.5),
            loudness,

            // Enhanced features
            bassLevel: Math.min(1, energy * (1 - brightness)),
            midLevel: Math.min(1, energy),
            trebleLevel: Math.min(1, energy * brightness),

            // Analysis features
            spectralCentroid: brightness,
            spectralRolloff: this.normalizeFeature(frame.spectralRolloff || 0, 'spectralRolloff', 8000),
            energy,
            rms,

            // Metadata
            timestamp: performance.now(),
            normalized: true,
            hasAdvancedFeatures: true,
            isPreAnalyzed: true
        };
    }

    /**
     * Normalize an analyzed feature against aggregate stats when available.
     */
    normalizeFeature(value, featureName, fallbackMax = 1) {
        if (!Number.isFinite(value)) {
            return 0;
        }

        const stats = this.getFeatureStats(featureName);

        if (stats && Number.isFinite(stats.max) && Number.isFinite(stats.min) && stats.max > stats.min) {
            return this.clamp01((value - stats.min) / (stats.max - stats.min));
        }

        if (value > 1) {
            return this.clamp01(value / fallbackMax);
        }

        return this.clamp01(value);
    }

    getFeatureStats(featureName) {
        const stats = this.currentAnalysis?.stats?.[featureName];

        if (!stats) {
            return null;
        }

        return stats.total || stats;
    }

    clamp01(value) {
        return Math.max(0, Math.min(1, value));
    }

    /**
     * Interpolate between current and previous audio data
     */
    interpolateAudioData(current, previous) {
        const interpolated = {};

        Object.keys(current).forEach(key => {
            if (typeof current[key] === 'number' && typeof previous[key] === 'number') {
                interpolated[key] = previous[key] * this.smoothingFactor +
                                  current[key] * (1 - this.smoothingFactor);
            } else {
                interpolated[key] = current[key];
            }
        });

        return interpolated;
    }

    /**
     * Get fallback data when analysis is unavailable
     */
    getFallbackData() {
        return {
            bass: 0, mid: 0, treble: 0, loudness: 0,
            bassLevel: 0, midLevel: 0, trebleLevel: 0,
            spectralCentroid: 0.5, spectralRolloff: 0.5,
            energy: 0, rms: 0,
            timestamp: performance.now(),
            normalized: true,
            hasAdvancedFeatures: false,
            isPreAnalyzed: false
        };
    }

    /**
     * Set playback start time for synchronization
     */
    setPlaybackStartTime(startTime) {
        this.playbackStartTime = startTime;
        this.lastFrameIndex = 0;
    }

    /**
     * Enable/disable interpolation
     */
    setInterpolation(enabled) {
        this.interpolationEnabled = enabled;
    }

    /**
     * Set smoothing factor for interpolation
     */
    setSmoothingFactor(factor) {
        this.smoothingFactor = Math.max(0, Math.min(1, factor));
    }

    /**
     * Clear cache and analysis data
     */
    dispose() {
        this.analysisCache.clear();
        this.currentAnalysis = null;
        this.lastInterpolatedData = null;
        dlog('📊 PreAnalyzedAudioLoader disposed');
    }
}

export default PreAnalyzedAudioLoader;
